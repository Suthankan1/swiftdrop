package com.swiftdrop.deliveryservice.assignment;

import com.swiftdrop.deliveryservice.core.Parcel;
import com.swiftdrop.deliveryservice.core.ParcelStatus;
import com.swiftdrop.deliveryservice.status.StatusHistory;
import jakarta.persistence.EntityManager;
import jakarta.persistence.PersistenceContext;
import jakarta.persistence.TypedQuery;
import jakarta.persistence.criteria.CriteriaBuilder;
import jakarta.persistence.criteria.CriteriaQuery;
import jakarta.persistence.criteria.Predicate;
import jakarta.persistence.criteria.Root;
import jakarta.persistence.criteria.Subquery;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageImpl;
import org.springframework.data.domain.Pageable;

import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Criteria-based implementation that omits absent filters instead of binding untyped nulls.
 * All caller values remain bind parameters generated by Hibernate.
 */
public class DeliveryAssignmentRepositoryImpl implements DeliveryAssignmentRepositoryCustom {

    private static final char LIKE_ESCAPE = '\\';

    @PersistenceContext
    private EntityManager entityManager;

    @Override
    public Page<DeliveryAssignment> findFilteredActiveByCourierSub(
            String courierSub,
            Instant assignedSince,
            String trackingNumber,
            ParcelStatus status,
            Pageable pageable) {
        CriteriaBuilder cb = entityManager.getCriteriaBuilder();
        CriteriaQuery<DeliveryAssignment> query = cb.createQuery(DeliveryAssignment.class);
        Root<DeliveryAssignment> assignment = query.from(DeliveryAssignment.class);

        query.select(assignment)
                .where(activePredicates(query, cb, assignment, courierSub, assignedSince, trackingNumber, status)
                        .toArray(Predicate[]::new))
                .orderBy(cb.desc(assignment.get("assignedAt")), cb.asc(assignment.get("assignmentId")));

        CriteriaQuery<Long> countQuery = cb.createQuery(Long.class);
        Root<DeliveryAssignment> countedAssignment = countQuery.from(DeliveryAssignment.class);
        countQuery.select(cb.count(countedAssignment))
                .where(activePredicates(countQuery, cb, countedAssignment, courierSub, assignedSince, trackingNumber, status)
                        .toArray(Predicate[]::new));

        return page(query, countQuery, pageable);
    }

    @Override
    public Page<DeliveryAssignment> findCourierHistory(
            String courierSub,
            ParcelStatus status,
            Instant completedSince,
            Instant completedUntil,
            Pageable pageable) {
        CriteriaBuilder cb = entityManager.getCriteriaBuilder();
        CriteriaQuery<DeliveryAssignment> query = cb.createQuery(DeliveryAssignment.class);
        Root<DeliveryAssignment> assignment = query.from(DeliveryAssignment.class);

        query.select(assignment)
                .where(historyPredicates(query, cb, assignment, courierSub, status, completedSince, completedUntil)
                        .toArray(Predicate[]::new))
                .orderBy(
                        cb.desc(assignment.get("endedAt")),
                        cb.desc(assignment.get("assignedAt")),
                        cb.asc(assignment.get("assignmentId")));

        CriteriaQuery<Long> countQuery = cb.createQuery(Long.class);
        Root<DeliveryAssignment> countedAssignment = countQuery.from(DeliveryAssignment.class);
        countQuery.select(cb.count(countedAssignment))
                .where(historyPredicates(countQuery, cb, countedAssignment, courierSub, status, completedSince, completedUntil)
                        .toArray(Predicate[]::new));

        return page(query, countQuery, pageable);
    }

    private List<Predicate> activePredicates(
            CriteriaQuery<?> query,
            CriteriaBuilder cb,
            Root<DeliveryAssignment> assignment,
            String courierSub,
            Instant assignedSince,
            String trackingNumber,
            ParcelStatus status) {
        List<Predicate> predicates = new ArrayList<>();
        predicates.add(cb.equal(assignment.get("courierSub"), courierSub));
        predicates.add(cb.isTrue(assignment.get("active")));

        if (assignedSince != null) {
            predicates.add(cb.greaterThanOrEqualTo(assignment.get("assignedAt"), assignedSince));
        }
        if (trackingNumber != null && !trackingNumber.isBlank()) {
            Subquery<Integer> parcelMatch = query.subquery(Integer.class);
            Root<Parcel> parcel = parcelMatch.from(Parcel.class);
            String pattern = "%" + escapeLike(trackingNumber.trim().toLowerCase(Locale.ROOT)) + "%";
            parcelMatch.select(cb.literal(1)).where(
                    cb.equal(parcel.get("parcelId"), assignment.get("parcelId")),
                    cb.like(cb.lower(parcel.get("trackingNumber")), pattern, LIKE_ESCAPE));
            predicates.add(cb.exists(parcelMatch));
        }
        if (status != null) {
            Subquery<Integer> parcelMatch = query.subquery(Integer.class);
            Root<Parcel> parcel = parcelMatch.from(Parcel.class);
            parcelMatch.select(cb.literal(1)).where(
                    cb.equal(parcel.get("parcelId"), assignment.get("parcelId")),
                    cb.equal(parcel.get("status"), status));
            predicates.add(cb.exists(parcelMatch));
        }
        return predicates;
    }

    private List<Predicate> historyPredicates(
            CriteriaQuery<?> query,
            CriteriaBuilder cb,
            Root<DeliveryAssignment> assignment,
            String courierSub,
            ParcelStatus status,
            Instant completedSince,
            Instant completedUntil) {
        List<Predicate> predicates = new ArrayList<>();
        predicates.add(cb.equal(assignment.get("courierSub"), courierSub));

        Subquery<Integer> terminalHistory = query.subquery(Integer.class);
        Root<StatusHistory> history = terminalHistory.from(StatusHistory.class);
        List<Predicate> historyPredicates = new ArrayList<>();
        historyPredicates.add(cb.equal(history.get("parcelId"), assignment.get("parcelId")));
        historyPredicates.add(cb.equal(history.get("actorSub"), assignment.get("courierSub")));
        historyPredicates.add(history.get("newStatus").in(ParcelStatus.DELIVERED, ParcelStatus.FAILED));
        historyPredicates.add(cb.greaterThanOrEqualTo(history.get("occurredAt"), assignment.get("assignedAt")));
        historyPredicates.add(cb.or(
                cb.isNull(assignment.get("endedAt")),
                cb.lessThanOrEqualTo(history.get("occurredAt"), assignment.get("endedAt"))));

        if (status != null) {
            historyPredicates.add(cb.equal(history.get("newStatus"), status));
        }
        if (completedSince != null) {
            historyPredicates.add(cb.greaterThanOrEqualTo(history.get("occurredAt"), completedSince));
        }
        if (completedUntil != null) {
            historyPredicates.add(cb.lessThan(history.get("occurredAt"), completedUntil));
        }

        terminalHistory.select(cb.literal(1)).where(historyPredicates.toArray(Predicate[]::new));
        predicates.add(cb.exists(terminalHistory));
        return predicates;
    }

    private Page<DeliveryAssignment> page(
            CriteriaQuery<DeliveryAssignment> query,
            CriteriaQuery<Long> countQuery,
            Pageable pageable) {
        TypedQuery<DeliveryAssignment> typedQuery = entityManager.createQuery(query);
        if (pageable.isPaged()) {
            typedQuery.setFirstResult(Math.toIntExact(pageable.getOffset()));
            typedQuery.setMaxResults(pageable.getPageSize());
        }
        long total = entityManager.createQuery(countQuery).getSingleResult();
        return new PageImpl<>(typedQuery.getResultList(), pageable, total);
    }

    private String escapeLike(String value) {
        return value
                .replace("\\", "\\\\")
                .replace("%", "\\%")
                .replace("_", "\\_");
    }
}
